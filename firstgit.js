function add(a, b) {
    return a + b;
}

function multiply(a, b) {
    return a * b;
}
console.log(add(10, 20));
console.log(multiply(10, 20));


function subtract(a, b) {
    return a - b;
}       
console.log(subtract(20, 10));

function divide(a, b) {
    return a / b;
}   
console.log(divide(20, 10));